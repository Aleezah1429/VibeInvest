// ─── main screen ───────────────────────────────────────────────────────────
export default function ReportScreen() {
  const router = useRouter();
  const { name, id } = useLocalSearchParams<{ name: string; id?: string }>();

  const [report, setReport] = useState<ReportData | null>(id ? null : PLACEHOLDER_REPORT);
  const [loadError, setLoadError] = useState<string | null>(null);

  // Save to dashboard's in-memory store on first load — guarded so the recent
  // list doesn't duplicate if the screen re-renders.
  const { addReport } = useReports();
  const savedRef = useRef(false);
  useEffect(() => {
    if (!report || savedRef.current) return;
    savedRef.current = true;
    const dims = report.dimensions.slice(0, 3).map((d) => ({ label: d.name, val: d.score }));
    addReport({
      name: report.startup_name,
      score: report.score,
      verdict: report.verdict,
      breakdowns: dims,
    });
  }, [report, addReport]);

  // Load real analysis when an id is passed.
  useEffect(() => {
    if (!id) return;
    let cancelled = false;
    getAnalysis(id)
      .then((a) => {
        if (cancelled) return;
        if (a.report) setReport(a.report);
        else if (a.status === 'failed') {
          setLoadError(a.error || 'Analysis failed.');
          setReport(PLACEHOLDER_REPORT);
        } else {
          setReport(PLACEHOLDER_REPORT);
        }
      })
      .catch((e) => {
        if (cancelled) return;
        setLoadError(e?.message || 'Could not load report.');
        setReport(PLACEHOLDER_REPORT);
      });
    return () => {
      cancelled = true;
    };
  }, [id]);

  // Animated score countup (0 → target over 1500ms with eased curve).
  const target = report?.score ?? 0;
  const startupName = report?.startup_name || name || 'Bykea';
  const [score, setScore] = useState(0);

  useEffect(() => {
    if (!report) return;
    const duration = 1500;
    const startTime = Date.now();
    let rafId: number;
    const animateScore = () => {
      const now = Date.now();
      const progress = Math.min((now - startTime) / duration, 1);
      const eased = 1 - Math.pow(1 - progress, 3);
      setScore(Math.round(eased * target));
      if (progress < 1) {
        rafId = requestAnimationFrame(animateScore);
      }
    };
    rafId = requestAnimationFrame(animateScore);
    return () => cancelAnimationFrame(rafId);
  }, [report, target]);

  // Expand/collapse state — first item open by default.
  const [expandedAgent, setExpandedAgent] = useState<number | null>(1);
  const [expandedDeliv, setExpandedDeliv] = useState<string | null>('brief');

  // Generate the PDF locally on-device (no backend round-trip needed) and
  // open the native share sheet so the user can save it to Files / Drive /
  // mail / WhatsApp. Works offline and on placeholder reports too.
  const handleDownloadPdf = async () => {
    if (!report) return;
    try {
      const html = buildReportHtml(report, startupName);
      const { uri } = await Print.printToFileAsync({ html, base64: false });
      if (await Sharing.isAvailableAsync()) {
        await Sharing.shareAsync(uri, {
          UTI: 'com.adobe.pdf',
          mimeType: 'application/pdf',
          dialogTitle: `${startupName} — Aura Report`,
        });
      } else {
        // Web / unsupported platform — fall back to opening the local URI.
        Linking.openURL(uri).catch(() => {
          Alert.alert('Saved', `PDF saved at:\n${uri}`);
        });
      }
    } catch (err) {
      Alert.alert(
        'Save failed',
        err instanceof Error ? err.message : 'Could not generate the PDF.',
      );
    }
  };

  const handleShare = async () => {
    if (!id) return;
    const pdfUrl = `${API_BASE_URL}/api/analyses/${id}/pdf`;
    if (Platform.OS === 'web') {
      try {
        if (navigator.clipboard) {
          await navigator.clipboard.writeText(pdfUrl);
          Alert.alert('Link Copied', 'The PDF report link has been copied to your clipboard.');
          return;
        }
      } catch {
        // fall through
      }
    }
    try {
      await Share.share({
        message: `VibeInvest due diligence for ${startupName}: ${pdfUrl}`,
        url: pdfUrl,
        title: `${startupName} Due Diligence Report`,
      });
    } catch {
      Alert.alert('Share Failed', 'Could not share the due diligence report.');
    }
  };

  if (!report) {
    return (
      <SafeAreaView style={[s.screen, { alignItems: 'center', justifyContent: 'center' }]}>
        <ActivityIndicator color={T.purple} />
        <Text style={s.loadingText}>loading report…</Text>
      </SafeAreaView>
    );
  }

  return (
    <SafeAreaView style={s.screen}>
      {/* ── header ── */}
      <View style={s.header}>
        <TouchableOpacity
          onPress={() => router.back()}
          style={s.headerBtn}
          accessibilityLabel="Back"
          hitSlop={10}
        >
          <Ionicons name="chevron-back" size={22} color={T.ink} />
        </TouchableOpacity>
        <Text style={s.headerTitle}>Report</Text>
        <View style={s.headerActions}>
          <TouchableOpacity
            onPress={handleShare}
            style={s.headerBtn}
            accessibilityLabel="Share report"
            hitSlop={10}
          >
            <Ionicons name="share-outline" size={20} color={T.ink} />
          </TouchableOpacity>
          <TouchableOpacity
            onPress={handleDownloadPdf}
            style={s.headerBtn}
            accessibilityLabel="Save report as PDF"
            hitSlop={10}
          >
            <Ionicons name="save-outline" size={20} color={T.ink} />
          </TouchableOpacity>
        </View>
      </View>

      <ScrollView contentContainerStyle={{ paddingBottom: 36 }} showsVerticalScrollIndicator={false}>
        {/* ── hero (aura score + verdict) ── */}
        <View style={{ paddingHorizontal: 20, marginTop: 14 }}>
          <View style={s.heroOuter}>
            <LinearGradient
              colors={['rgba(40,24,72,0.65)', 'rgba(14,11,24,0.85)']}
              locations={[0, 0.6]}
              start={{ x: 0.3, y: 0 }}
              end={{ x: 0.7, y: 1 }}
              style={s.hero}
            >
              <Text style={s.eyebrow}>◢ AURA SCORE · FINAL</Text>
              <Text style={s.startupName}>{startupName}</Text>

              <View style={s.heroRingWrap}>
                <AuraRing score={score} size={184} />
                <View style={s.heroRingCenter} pointerEvents="none">
                  <Text style={s.bigScore}>{score}</Text>
                  <Text style={s.scoreMax}>/ 1000</Text>
                </View>
              </View>

              <VerdictPill verdict={report.verdict} sub={report.verdict_sub ?? undefined} />

              {/* tags */}
              {report.tags.length > 0 && (
                <View style={s.tagsRow}>
                  {report.tags.slice(0, 5).map((t, i) => (
                    <View key={`${t}-${i}`} style={s.tag}>
                      <Text style={s.tagText}>{t}</Text>
                    </View>
                  ))}
                </View>
              )}

              <View style={s.heroFootRow}>
                <Text style={s.heroFootText}>⌁ Confidence 0.91 · 4/4 agents</Text>
              </View>
            </LinearGradient>
          </View>

          {loadError && (
            <Text style={s.loadErrorText}>showing placeholder · {loadError}</Text>
          )}
        </View>

        {/* ── dimensions ── */}
        <View style={s.section}>
          <SectionHead eyebrow="◢ DIMENSIONS" title="Score breakdown" />
          <View style={{ gap: 12 }}>
            {report.dimensions.map((d) => (
              <DimBar key={d.name} name={d.name} score={d.score} />
            ))}
          </View>
        </View>

        {/* ── key metrics ── */}
        <View style={s.section}>
          <SectionHead eyebrow="◢ KEY METRICS" title="By the numbers" />
          {report.metrics.length === 0 ? (
            <Text style={s.emptyText}>No metrics surfaced.</Text>
          ) : (
            <View style={s.metricsGrid}>
              {report.metrics.map((m, i) => (
                <MetricCard
                  key={`${m.label}-${i}`}
                  label={m.label}
                  value={m.value}
                  change={m.change}
                  changeColor={findingColor(m.change_type)}
                />
              ))}
            </View>
          )}
        </View>

        {/* ── agent reports ── */}
        <View style={s.section}>
          <SectionHead eyebrow="◢ AGENT REPORTS" title="What each agent found" />
          {report.agent_reports.length === 0 ? (
            <Text style={s.emptyText}>No agent reports yet.</Text>
          ) : (
            <View style={{ gap: 10 }}>
              {report.agent_reports.map((r: AgentReport) => (
                <AgentCard
                  key={r.id}
                  agentId={r.id}
                  name={r.name}
                  role={r.role}
                  badge={r.badge || '—'}
                  body={r.body}
                  findings={r.findings.map((f) => ({ text: f.text, color: findingColor(f.type) }))}
                  expanded={expandedAgent === r.id}
                  onToggle={() => setExpandedAgent(expandedAgent === r.id ? null : r.id)}
                />
              ))}
            </View>
          )}
        </View>

        {/* ── deliverables ── */}
        <View style={s.section}>
          <SectionHead
            eyebrow="◢ DELIVERABLES"
            title="Generate"
            meta={
              <View style={s.cvoAutoRow}>
                <Sparkles size={11} color={T.purple} style={{ marginRight: 4 }} />
                <Text style={s.cvoAuto}>CVO AUTO-GENERATED</Text>
              </View>
            }
          />
          <View style={{ gap: 10 }}>
            {DELIVERABLES.map((item) => (
              <DeliverableItem
                key={item.key}
                item={item}
                bullets={buildBullets(report, item.key)}
                expanded={expandedDeliv === item.key}
                onToggle={() => setExpandedDeliv(expandedDeliv === item.key ? null : item.key)}
              />
            ))}
          </View>
        </View>

        {/* ── CTA ── */}
        <View style={{ paddingHorizontal: 20, marginTop: 28 }}>
          <TouchableOpacity
            onPress={() => router.push('/')}
            accessibilityLabel="Start a new analysis"
            activeOpacity={0.85}
            style={s.ctaTouchable}
          >
            <LinearGradient
              colors={['#9550ee', '#7b3bd9']}
              start={{ x: 0, y: 0 }}
              end={{ x: 0, y: 1 }}
              style={s.cta}
            >
              <Text style={s.ctaText}>New Analysis</Text>
              <Ionicons name="arrow-forward" size={16} color="#fff" style={{ marginLeft: 8 }} />
            </LinearGradient>
          </TouchableOpacity>
        </View>
      </ScrollView>
    </SafeAreaView>
  );
}

