// ─── aura ring (svg) ───────────────────────────────────────────────────────
function AuraRing({ score, max = 1000, size = 168 }: { score: number; max?: number; size?: number }) {
  const r = (size - 20) / 2;
  const C0 = 2 * Math.PI * r;
  const pct = Math.max(0, Math.min(1, score / max));
  const offset = C0 * (1 - pct);
  return (
    <Svg width={size} height={size} viewBox={`0 0 ${size} ${size}`}>
      <Defs>
        <SvgLinearGradient id="auraRingReport" x1="0" y1="0" x2="1" y2="1">
          <Stop offset="0%" stopColor="#c79bff" />
          <Stop offset="50%" stopColor="#9550ee" />
          <Stop offset="100%" stopColor="#5b2ea3" />
        </SvgLinearGradient>
      </Defs>
      <Circle cx={size / 2} cy={size / 2} r={r} stroke="rgba(255,255,255,0.06)" strokeWidth={6} fill="none" />
      {score > 0 && (
        <Circle
          cx={size / 2}
          cy={size / 2}
          r={r}
          stroke="url(#auraRingReport)"
          strokeWidth={6}
          fill="none"
          strokeLinecap="round"
          strokeDasharray={C0}
          strokeDashoffset={offset}
          transform={`rotate(-90 ${size / 2} ${size / 2})`}
        />
      )}
    </Svg>
  );
}

